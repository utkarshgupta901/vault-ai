"""Freeze the demo user's suggested questions into evals/golden_starters.yaml (XF 27).

    uv run python scripts/freeze_starters.py [--api http://localhost:8000] [--key vault-demo-key]

The UI offers each document's AI-generated suggested questions as starter chips. They come from the model, so they
change when insights are regenerated; freezing them (together with the demo snapshot) means the exact starters shown
on demo day are also tested by the eval. A starter passes when it is answered (not refused) with at least one valid
citation and no ungrounded numbers (expect: min_citations 1, grounded true).

Starter cases are tagged `starter` and `demo`, so `make eval-demo` runs them 3x like the scripted demo questions.
Re-running overwrites the file."""

import argparse
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import httpx  # noqa: E402
import yaml  # noqa: E402

from evals.api_client import API_PREFIX, ApiError, VaultClient  # noqa: E402
from evals.golden import STARTERS_PATH  # noqa: E402

HEADER = """\
# Frozen starter questions (generated by scripts/freeze_starters.py; do not edit by hand, re-run it instead).
# Source: each ready document's insights.suggested_questions for the demo user, at the time of the demo snapshot.
# A starter passes when it is answered with >= 1 valid citation and no ungrounded facts.
"""


def slug(filename: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", Path(filename).stem.lower()).strip("-")


def starter_cases(filename: str, questions: list[str]) -> list[dict[str, Any]]:
    return [{"id": f"starter-{slug(filename)}-{i}", "question": q, "tags": ["starter", "demo"], "scope": [filename],
             "expect": {"not_found": False, "min_citations": 1, "grounded": True}}
            for i, q in enumerate(questions, start=1) if q.strip()]


def collect(client: VaultClient) -> list[dict[str, Any]]:
    cases: list[dict[str, Any]] = []
    seen: set[str] = set()
    for doc in sorted(client.list_documents(), key=lambda d: d["filename"]):
        if doc["status"] != "ready" or doc.get("insights_status") != "ready" or doc["filename"] in seen:
            continue
        seen.add(doc["filename"])
        insights = client.get_json(f"{API_PREFIX}/documents/{doc['id']}/insights").get("insights") or {}
        cases += starter_cases(doc["filename"], list(insights.get("suggested_questions") or []))
    return cases


def write(cases: list[dict[str, Any]], path: Path) -> None:
    body = yaml.safe_dump(cases, sort_keys=False, allow_unicode=True, width=120)
    path.write_text(HEADER + body, encoding="utf-8")


def main(argv: list[str] | None = None, *, transport: Any = None) -> int:
    p = argparse.ArgumentParser(description="Freeze suggested questions into evals/golden_starters.yaml.")
    p.add_argument("--api", default="http://localhost:8000")
    p.add_argument("--key", default="vault-demo-key")
    p.add_argument("--out", type=Path, default=STARTERS_PATH)
    args = p.parse_args(argv)
    try:
        with VaultClient(args.api, args.key, transport=transport) as client:
            cases = collect(client)
    except (ApiError, httpx.HTTPError) as exc:
        print(f"could not read insights: {exc}", file=sys.stderr)
        return 1
    if not cases:
        print("no ready documents with insights found; run scripts/seed_demo.py first", file=sys.stderr)
        return 1
    write(cases, args.out)
    print(f"wrote {len(cases)} starter cases from {len({c['scope'][0] for c in cases})} documents to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
